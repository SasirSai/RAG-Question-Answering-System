"""LLM generation and provider completion supporting Gemini, Anthropic, and Ollama."""

import time
from typing import Any, Dict, List, Optional, Tuple
import httpx

import config

SYSTEM_PROMPT = (
    "You are a factual question-answering assistant. Answer the user's question ONLY using the provided "
    "context passages. Cite your sources using the exact format [doc_id, chunk_id] whenever stating facts. "
    "If the provided context does not contain sufficient information to answer the question, state plainly: "
    "'The provided documents do not contain enough information to answer this question.' "
    "Do not extrapolate or speculate beyond the provided context."
)


def build_prompt(question: str, chunks: List[Dict[str, Any]]) -> str:
    """Constructs prompt containing system instructions, numbered context chunks, and user query."""
    context_blocks = []
    for idx, c in enumerate(chunks, start=1):
        doc_id = c.get("doc_id", "unknown")
        chunk_id = c.get("chunk_id", "unknown")
        page = c.get("page")
        page_str = f", page {page}" if page is not None else ""
        text = c.get("text", "").strip()
        context_blocks.append(f"Passage {idx} [{doc_id}, {chunk_id}{page_str}]:\n{text}")

    joined_context = "\n\n".join(context_blocks)
    prompt = (
        f"{SYSTEM_PROMPT}\n\n"
        f"--- CONTEXT ---\n"
        f"{joined_context}\n"
        f"--- END CONTEXT ---\n\n"
        f"Question: {question}\n\n"
        f"Answer:"
    )
    return prompt


def _complete_gemini(prompt: str, api_key: str) -> str:
    """Calls Gemini REST API with 1 retry on rate limit / server error."""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
    payload = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"temperature": 0.0},
    }

    for attempt in range(2):
        try:
            with httpx.Client(timeout=30.0) as client:
                res = client.post(url, json=payload)
                res.raise_for_status()
                data = res.json()
                candidates = data.get("candidates", [])
                if candidates and "content" in candidates[0]:
                    parts = candidates[0]["content"].get("parts", [])
                    if parts:
                        return parts[0].get("text", "").strip()
                return "No response generated by Gemini."
        except Exception as e:
            if attempt == 0:
                time.sleep(1.5)
                continue
            raise RuntimeError(f"Gemini API error after 1 retry: {e}") from e
    return ""


def _complete_anthropic(prompt: str, api_key: str) -> str:
    """Calls Anthropic Messages API with 1 retry on rate limit / server error."""
    url = "https://api.anthropic.com/v1/messages"
    headers = {
        "x-api-key": api_key,
        "anthropic-version": "2023-06-01",
        "content-type": "application/json",
    }
    payload = {
        "model": "claude-3-haiku-20240307",
        "max_tokens": 1024,
        "temperature": 0.0,
        "messages": [{"role": "user", "content": prompt}],
    }

    for attempt in range(2):
        try:
            with httpx.Client(timeout=30.0) as client:
                res = client.post(url, headers=headers, json=payload)
                res.raise_for_status()
                data = res.json()
                content = data.get("content", [])
                if content and "text" in content[0]:
                    return content[0]["text"].strip()
                return "No response generated by Anthropic."
        except Exception as e:
            if attempt == 0:
                time.sleep(1.5)
                continue
            raise RuntimeError(f"Anthropic API error after 1 retry: {e}") from e
    return ""


def _complete_ollama(prompt: str, base_url: str, model: str) -> str:
    """Calls local Ollama instance with 1 retry."""
    url = f"{base_url.rstrip('/')}/api/generate"
    payload = {
        "model": model,
        "prompt": prompt,
        "stream": False,
        "options": {"temperature": 0.0},
    }

    for attempt in range(2):
        try:
            with httpx.Client(timeout=45.0) as client:
                res = client.post(url, json=payload)
                res.raise_for_status()
                data = res.json()
                return data.get("response", "").strip()
        except Exception as e:
            if attempt == 0:
                time.sleep(1.5)
                continue
            raise RuntimeError(f"Ollama API error after 1 retry: {e}") from e
    return ""


def complete(prompt: str) -> Optional[str]:
    """Provider router behind a single swappable complete(prompt) function."""
    provider = config.LLM_PROVIDER
    if not provider:
        return None

    if provider == "gemini":
        if not config.GEMINI_API_KEY:
            return None
        return _complete_gemini(prompt, config.GEMINI_API_KEY)
    elif provider == "anthropic":
        if not config.ANTHROPIC_API_KEY:
            return None
        return _complete_anthropic(prompt, config.ANTHROPIC_API_KEY)
    elif provider == "ollama":
        return _complete_ollama(prompt, config.OLLAMA_BASE_URL, config.OLLAMA_MODEL)
    else:
        raise ValueError(f"Unknown LLM_PROVIDER: '{provider}'. Supported: 'gemini', 'anthropic', 'ollama'.")


def generate_answer(question: str, chunks: List[Dict[str, Any]]) -> Tuple[Optional[str], Optional[str]]:
    """Generates an answer from top chunks or falls back cleanly to retrieval-only mode."""
    if not chunks:
        return "No relevant passages found in corpus.", None

    prompt = build_prompt(question, chunks)
    try:
        answer = complete(prompt)
        if answer is None:
            return None, "Retrieval-only mode: no LLM provider or API key configured."
        return answer, None
    except Exception as e:
        return None, f"LLM generation failed ({str(e)}). Falling back to retrieval-only mode."
